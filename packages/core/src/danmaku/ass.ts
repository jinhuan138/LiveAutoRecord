/**
 * 把录制时保存的弹幕（RecordExtraData）转换为 ASS 字幕，用于压制带弹幕的视频，
 * 也可以直接作为外挂字幕给本地播放器使用（同名 .ass 会被大部分播放器自动加载）。
 *
 * 目前只实现了从右向左滚动的弹幕，排列方式参考了 danmaku2ass：
 * 把画面按行高切成若干条轨道，每条弹幕找一条不会与前一条弹幕重叠的轨道，都放不下时丢弃。
 */
import type { Comment, RecordExtraData } from '@autorecord/manager'
import type { DanmakuStyle } from '@autorecord/shared'

/** 以 1080p 作为画布高度，这样字号等参数与实际视频分辨率无关，libass 会负责等比缩放 */
const PLAY_RES_Y = 1080

export function getDefaultDanmakuFontName(): string {
  switch (process.platform) {
    case 'win32':
      return 'Microsoft YaHei'
    case 'darwin':
      return 'PingFang SC'
    default:
      return 'Noto Sans CJK SC'
  }
}

export function resolveDanmakuStyle(style: DanmakuStyle = {}): Required<DanmakuStyle> {
  return {
    fontName: style.fontName?.trim() || getDefaultDanmakuFontName(),
    fontSize: clamp(toNumber(style.fontSize, 48), 12, 200),
    opacity: clamp(toNumber(style.opacity, 0.8), 0, 1),
    scrollDuration: clamp(toNumber(style.scrollDuration, 10), 1, 60),
    displayAreaRatio: clamp(toNumber(style.displayAreaRatio, 0.5), 0.05, 1),
    timeOffset: toNumber(style.timeOffset, 0),
  }
}

/** 设置来自用户输入，可能是空字符串、数字字符串等 */
function toNumber(value: unknown, defaultValue: number): number {
  if (typeof value === 'number' && Number.isFinite(value)) return value
  if (typeof value === 'string' && value.trim() !== '' && Number.isFinite(Number(value))) return Number(value)
  return defaultValue
}

export interface GenerateDanmakuASSOpts {
  /** 视频分辨率，只用于计算画面比例，缺省时按 16:9 处理 */
  videoWidth?: number
  videoHeight?: number
  style?: DanmakuStyle
}

export interface GenerateDanmakuASSResult {
  content: string
  /** 参与排列的弹幕总数 */
  total: number
  /** 实际写入 ASS 的弹幕数，其余因为屏幕放不下被丢弃 */
  rendered: number
}

interface TrackSlot {
  start: number
  width: number
  speed: number
}

export function generateDanmakuASS(
  extraData: RecordExtraData,
  opts: GenerateDanmakuASSOpts = {},
): GenerateDanmakuASSResult {
  const style = resolveDanmakuStyle(opts.style)
  const aspectRatio =
    opts.videoWidth && opts.videoHeight && opts.videoWidth > 0 && opts.videoHeight > 0
      ? opts.videoWidth / opts.videoHeight
      : 16 / 9
  const playResX = Math.round(PLAY_RES_Y * aspectRatio)

  const { fontSize, scrollDuration } = style
  const lineHeight = Math.ceil(fontSize * 1.25)
  const trackCount = Math.max(1, Math.floor((PLAY_RES_Y * style.displayAreaRatio) / lineHeight))
  const tracks: (TrackSlot | undefined)[] = new Array(trackCount)
  // 同一轨道上两条弹幕之间至少保留的水平间距
  const gap = fontSize

  const startTimestamp = extraData.meta.recordStartTimestamp
  const comments = extraData.messages
    .filter((msg): msg is Comment => msg.type === 'comment' && msg.text.trim() !== '')
    .map((msg) => ({ msg, start: (msg.timestamp - startTimestamp + style.timeOffset) / 1e3 }))
    .filter((item) => item.start >= 0)
    .sort((a, b) => a.start - b.start)

  const events: string[] = []
  for (const { msg, start } of comments) {
    const text = normalizeText(msg.text)
    const width = estimateTextWidth(text, fontSize)
    const speed = (playResX + width) / scrollDuration

    const trackIdx = findAvailableTrack(tracks, start, width, speed, playResX, scrollDuration, gap)
    if (trackIdx === -1) continue
    tracks[trackIdx] = { start, width, speed }

    const y = trackIdx * lineHeight
    const overrides = [`\\move(${playResX},${y},${-Math.ceil(width)},${y})`]
    const colorTag = toASSColorTag(msg.color)
    if (colorTag) overrides.push(colorTag)

    events.push(
      `Dialogue: 0,${formatTime(start)},${formatTime(start + scrollDuration)},Danmaku,,0,0,0,,{${overrides.join('')}}${escapeText(text)}`,
    )
  }

  const alpha = toHexByte(Math.round((1 - style.opacity) * 255))
  const content = [
    '[Script Info]',
    '; Generated by LiveAutoRecord',
    'ScriptType: v4.00+',
    `PlayResX: ${playResX}`,
    `PlayResY: ${PLAY_RES_Y}`,
    'WrapStyle: 2',
    'ScaledBorderAndShadow: yes',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: Danmaku,${style.fontName.replace(/,/g, '')},${fontSize},&H${alpha}FFFFFF,&H${alpha}FFFFFF,&H${alpha}000000,&H${alpha}000000,-1,0,0,0,100,100,0,0,1,${(fontSize / 24).toFixed(1)},0,7,0,0,0,1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
    ...events,
    '',
  ].join('\n')

  return { content, total: comments.length, rendered: events.length }
}

/**
 * 找一条可以放下新弹幕的轨道，需要同时满足：
 * 1. 前一条弹幕的尾部已经完全进入屏幕（并留出间距），新弹幕出现时不会与它重叠；
 * 2. 新弹幕如果比前一条更快，到达屏幕左侧之前不会追上前一条弹幕的尾部。
 */
function findAvailableTrack(
  tracks: (TrackSlot | undefined)[],
  start: number,
  width: number,
  speed: number,
  screenWidth: number,
  duration: number,
  gap: number,
): number {
  for (let i = 0; i < tracks.length; i++) {
    const last = tracks[i]
    if (last == null) return i

    const lastTailEnteredAt = last.start + (last.width + gap) / last.speed
    if (start < lastTailEnteredAt) continue

    const lastLeaveAt = last.start + duration
    const reachLeftAt = start + screenWidth / speed
    if (reachLeftAt < lastLeaveAt) continue

    return i
  }
  return -1
}

/** 粗略估算文字渲染宽度：全角字符、emoji 按 1 个字号算，其余按 0.6 个字号算，宁可偏大避免重叠 */
function estimateTextWidth(text: string, fontSize: number): number {
  let width = 0
  for (const char of text) {
    const code = char.codePointAt(0) ?? 0
    width += code >= 0x2e80 ? fontSize : fontSize * 0.6
  }
  return width
}

function normalizeText(text: string): string {
  return text.replace(/[\r\n]+/g, ' ').trim()
}

/**
 * ASS 中的 { } 会被当作样式标签，需要转义为 \{ \}；
 * libass 只把 \n \N \h \{ \} 当作转义，其他的 \ 会原样显示，所以只需要打断 \n \N \h 这几种组合。
 */
function escapeText(text: string): string {
  return text
    .replace(/\\(?=[nNh])/g, '\\\u200b')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
}

/** 只处理非白色的 #RRGGBB，白色就是默认样式，不需要额外的标签 */
function toASSColorTag(color?: string): string | null {
  if (!color) return null
  const matched = /^#?([0-9a-f]{6})$/i.exec(color.trim())
  if (!matched) return null
  const hex = matched[1].toUpperCase()
  if (hex === 'FFFFFF') return null
  const [r, g, b] = [hex.slice(0, 2), hex.slice(2, 4), hex.slice(4, 6)]
  return `\\c&H${b}${g}${r}&`
}

/** ASS 的时间格式为 H:MM:SS.cc */
function formatTime(seconds: number): string {
  const totalCentiseconds = Math.max(0, Math.round(seconds * 100))
  const cs = totalCentiseconds % 100
  const totalSeconds = Math.floor(totalCentiseconds / 100)
  const s = totalSeconds % 60
  const m = Math.floor(totalSeconds / 60) % 60
  const h = Math.floor(totalSeconds / 3600)
  return `${h}:${pad2(m)}:${pad2(s)}.${pad2(cs)}`
}

function pad2(num: number): string {
  return num.toString().padStart(2, '0')
}

function toHexByte(num: number): string {
  return clamp(num, 0, 255).toString(16).toUpperCase().padStart(2, '0')
}

function clamp(num: number, min: number, max: number): number {
  if (Number.isNaN(num)) return min
  return Math.min(max, Math.max(min, num))
}
